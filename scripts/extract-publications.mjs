import { readFileSync, writeFileSync } from 'node:fs'
import { parseHTML } from 'linkedom'

const src = readFileSync('scripts/source-pages/scientific-publications.html', 'utf8')
const { document } = parseHTML(src)

// The publications are the <li> items inside the ONE <ol> on this page.
const ol =
  document.querySelector('section.scientific-publication-content ol') ||
  document.querySelector('ol')

const items = [...ol.querySelectorAll(':scope > li')].map((li, i) => ({
  n: i + 1,
  text: li.textContent.replace(/\s+/g, ' ').trim(),
}))

if (items.length < 95) throw new Error(`only found ${items.length} publications`)

const body =
  `import type { Publication } from './types'\n\n` +
  `// Generated by scripts/extract-publications.mjs from the source page — do not hand-edit.\n` +
  `export const publications: Publication[] = ${JSON.stringify(items, null, 2)}\n`

writeFileSync('src/content/publications.ts', body)
console.log(`wrote ${items.length} publications`)
